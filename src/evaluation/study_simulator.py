"""Generate reproducible synthetic scenario metrics for pipeline testing.

These are software-integration checks, NOT novice/experienced human results.
"""
from pathlib import Path
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
SCENARIOS = ROOT / "data" / "evaluation" / "analyst_sessions_template.csv"

REQUIRED = [
    "session_id", "analyst_type", "scenario_id", "assistant_used",
    "procedure_adherence_pct", "missed_steps", "evidence_completeness_pct",
    "decision_accuracy_pct", "investigation_time_sec", "critical_errors", "notes"
]

def validate_template(path=SCENARIOS):
    df = pd.read_csv(path)
    missing = [c for c in REQUIRED if c not in df.columns]
    if missing:
        raise ValueError(f"Missing evaluation columns: {missing}")
    return df

if __name__ == "__main__":
    df = validate_template()
    print(f"Evaluation template validated: {len(df)} rows, {len(df.columns)} columns")
    print("No human-study results are generated by this script.")
